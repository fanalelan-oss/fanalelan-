export function getFAQsByService(serviceSlug: string): FAQItem[] {
  return initialFAQs.filter((faq) => faq.serviceSlug === serviceSlug);
}

export function searchFAQs(query: string): FAQItem[] {
  if (!query || query.trim() === "") return initialFAQs;
  const cleanQuery = query.toLowerCase().trim();
  return initialFAQs.filter(
    (faq) =>
      faq.question.toLowerCase().includes(cleanQuery) ||
      faq.answer.toLowerCase().includes(cleanQuery) ||
      faq.category.toLowerCase().includes(cleanQuery) ||
      faq.tags.some((tag) => tag.toLowerCase().includes(cleanQuery))
  );
}
